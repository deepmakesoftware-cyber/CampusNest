-- V7 (Phase 8): reviews, reports and owner identity verification records.

-- A student's review of a listing. Only students who sent an enquiry about the listing may review it; the stay
-- itself cannot be verified, so reviews are always labelled "stay not verified" in the UI.
CREATE TABLE reviews (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    listing_id     BIGINT        NOT NULL REFERENCES listings (id) ON DELETE CASCADE,
    student_id     BIGINT        NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    rating         INTEGER       NOT NULL,
    comment        VARCHAR(1000),
    status         VARCHAR(20)   NOT NULL DEFAULT 'VISIBLE',
    hidden_reason  VARCHAR(500),
    created_at     TIMESTAMPTZ   NOT NULL DEFAULT now(),
    updated_at     TIMESTAMPTZ   NOT NULL DEFAULT now(),
    CONSTRAINT uq_reviews_listing_student UNIQUE (listing_id, student_id),
    CONSTRAINT ck_reviews_rating CHECK (rating BETWEEN 1 AND 5),
    CONSTRAINT ck_reviews_status CHECK (status IN ('VISIBLE', 'HIDDEN'))
);

CREATE INDEX ix_reviews_listing ON reviews (listing_id, status);

-- Reports from users about a listing, a review or another user. target_id has no foreign key because it points at
-- different tables depending on target_type (checked by the service); this keeps one simple moderation queue.
CREATE TABLE reports (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reporter_id      BIGINT        NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    target_type      VARCHAR(20)   NOT NULL,
    target_id        BIGINT        NOT NULL,
    reason           VARCHAR(30)   NOT NULL,
    details          VARCHAR(1000),
    status           VARCHAR(20)   NOT NULL DEFAULT 'OPEN',
    resolved_by      BIGINT        REFERENCES users (id),
    resolution_note  VARCHAR(1000),
    created_at       TIMESTAMPTZ   NOT NULL DEFAULT now(),
    resolved_at      TIMESTAMPTZ,
    CONSTRAINT ck_reports_target CHECK (target_type IN ('LISTING', 'REVIEW', 'USER')),
    CONSTRAINT ck_reports_reason CHECK (reason IN ('FAKE_LISTING', 'WRONG_INFORMATION', 'UNSAFE', 'SPAM',
        'HARASSMENT', 'INAPPROPRIATE', 'OTHER')),
    CONSTRAINT ck_reports_status CHECK (status IN ('OPEN', 'UPHELD', 'DISMISSED'))
);

CREATE INDEX ix_reports_status ON reports (status, created_at);
CREATE INDEX ix_reports_target ON reports (target_type, target_id, status);
-- One open report per reporter per target.
CREATE UNIQUE INDEX uq_reports_open ON reports (reporter_id, target_type, target_id) WHERE status = 'OPEN';

-- Owner identity verification. No ID documents are stored (decision D4): the admin records HOW they checked.
ALTER TABLE owner_profiles ADD COLUMN verification_requested_at TIMESTAMPTZ;

CREATE TABLE verification_records (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_id     BIGINT        NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    decision     VARCHAR(20)   NOT NULL,
    method       VARCHAR(30)   NOT NULL,
    notes        VARCHAR(1000) NOT NULL,
    reviewer_id  BIGINT        NOT NULL REFERENCES users (id),
    created_at   TIMESTAMPTZ   NOT NULL DEFAULT now(),
    CONSTRAINT ck_vr_decision CHECK (decision IN ('VERIFIED', 'REJECTED', 'REVOKED')),
    CONSTRAINT ck_vr_method CHECK (method IN ('PHONE_CALL', 'VIDEO_CALL', 'IN_PERSON_VISIT', 'DOCUMENT_SEEN_NOT_STORED', 'OTHER'))
);

CREATE INDEX ix_verification_records_owner ON verification_records (owner_id, created_at);
