-- V3 (Phase 4): students saving listings and private enquiry threads between a student and an owner.

CREATE TABLE saved_listings (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id  BIGINT      NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    listing_id  BIGINT      NOT NULL REFERENCES listings (id) ON DELETE CASCADE,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT uq_saved_listings UNIQUE (student_id, listing_id)
);

-- One thread per (listing, student). Contact details are shared only when that person opts in.
CREATE TABLE enquiries (
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    listing_id              BIGINT      NOT NULL REFERENCES listings (id) ON DELETE CASCADE,
    student_id              BIGINT      NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    student_shares_contact  BOOLEAN     NOT NULL DEFAULT FALSE,
    owner_shares_contact    BOOLEAN     NOT NULL DEFAULT FALSE,
    created_at              TIMESTAMPTZ NOT NULL DEFAULT now(),
    last_message_at         TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT uq_enquiries_listing_student UNIQUE (listing_id, student_id)
);

CREATE INDEX ix_enquiries_student ON enquiries (student_id, last_message_at DESC);
CREATE INDEX ix_enquiries_listing ON enquiries (listing_id);

CREATE TABLE enquiry_messages (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    enquiry_id  BIGINT        NOT NULL REFERENCES enquiries (id) ON DELETE CASCADE,
    sender_id   BIGINT        NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    body        VARCHAR(2000) NOT NULL,
    created_at  TIMESTAMPTZ   NOT NULL DEFAULT now()
);

CREATE INDEX ix_enquiry_messages_enquiry ON enquiry_messages (enquiry_id, id);
