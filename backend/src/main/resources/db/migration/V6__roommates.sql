-- V6 (Phase 7): opt-in roommate profiles, connection requests and blocks.

-- One per student who chooses to look for a roommate. Only profiles with discoverable = TRUE are ever shown.
CREATE TABLE roommate_profiles (
    user_id                  BIGINT       PRIMARY KEY REFERENCES users (id) ON DELETE CASCADE,
    discoverable             BOOLEAN      NOT NULL DEFAULT FALSE,
    budget_min               INTEGER      NOT NULL,
    budget_max               INTEGER      NOT NULL,
    preferred_localities     VARCHAR(500) NOT NULL DEFAULT '',
    anywhere_near_college    BOOLEAN      NOT NULL DEFAULT FALSE,
    sleep_schedule           VARCHAR(20)  NOT NULL,
    smoking                  VARCHAR(20)  NOT NULL,
    cannot_live_with_smoker  BOOLEAN      NOT NULL DEFAULT FALSE,
    study_environment        VARCHAR(20)  NOT NULL,
    cleanliness              INTEGER      NOT NULL,
    guests                   INTEGER      NOT NULL,
    food_preference          VARCHAR(20),
    sharing_size             VARCHAR(20)  NOT NULL,
    same_gender_only         BOOLEAN      NOT NULL DEFAULT FALSE,
    about                    VARCHAR(300),
    updated_at               TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT ck_rm_budget      CHECK (budget_min >= 1000 AND budget_max <= 200000 AND budget_min <= budget_max),
    CONSTRAINT ck_rm_sleep       CHECK (sleep_schedule IN ('EARLY', 'REGULAR', 'LATE')),
    CONSTRAINT ck_rm_smoking     CHECK (smoking IN ('NON_SMOKER', 'OUTDOOR_SMOKER', 'SMOKER')),
    CONSTRAINT ck_rm_study       CHECK (study_environment IN ('QUIET', 'MODERATE', 'LIVELY')),
    CONSTRAINT ck_rm_clean       CHECK (cleanliness BETWEEN 1 AND 5),
    CONSTRAINT ck_rm_guests      CHECK (guests BETWEEN 1 AND 5),
    CONSTRAINT ck_rm_food        CHECK (food_preference IN ('VEG', 'EGGETARIAN', 'NON_VEG', 'VEGAN', 'NO_PREFERENCE')),
    CONSTRAINT ck_rm_sharing     CHECK (sharing_size IN ('ONE_ROOMMATE', 'TWO_OR_MORE', 'EITHER'))
);

CREATE INDEX ix_roommate_profiles_discoverable ON roommate_profiles (discoverable);

CREATE TABLE roommate_requests (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    from_user_id  BIGINT       NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    to_user_id    BIGINT       NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    status        VARCHAR(20)  NOT NULL DEFAULT 'PENDING',
    message       VARCHAR(500),
    created_at    TIMESTAMPTZ  NOT NULL DEFAULT now(),
    responded_at  TIMESTAMPTZ,
    CONSTRAINT ck_rr_status CHECK (status IN ('PENDING', 'ACCEPTED', 'DECLINED', 'WITHDRAWN')),
    CONSTRAINT ck_rr_not_self CHECK (from_user_id <> to_user_id)
);

-- At most one pending-or-accepted connection between any two students, whichever of them asked first.
CREATE UNIQUE INDEX uq_rr_active_pair ON roommate_requests (LEAST(from_user_id, to_user_id), GREATEST(from_user_id, to_user_id))
    WHERE status IN ('PENDING', 'ACCEPTED');
CREATE INDEX ix_rr_to ON roommate_requests (to_user_id, status);
CREATE INDEX ix_rr_from ON roommate_requests (from_user_id, status);

-- A block hides both students from each other's matches and stops requests between them.
CREATE TABLE roommate_blocks (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    blocker_id  BIGINT      NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    blocked_id  BIGINT      NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT uq_roommate_blocks UNIQUE (blocker_id, blocked_id),
    CONSTRAINT ck_rb_not_self CHECK (blocker_id <> blocked_id)
);
