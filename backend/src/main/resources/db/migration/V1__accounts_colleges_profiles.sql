-- V1 (Phase 2): user accounts, colleges, and the role-specific profile tables.
-- Never edit this file after it has been applied; add a new V2__...sql migration instead.

CREATE TABLE colleges (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(200)  NOT NULL,
    short_name  VARCHAR(30)   NOT NULL,
    address     VARCHAR(300)  NOT NULL,
    city        VARCHAR(80)   NOT NULL,
    latitude    NUMERIC(9, 6) NOT NULL,
    longitude   NUMERIC(9, 6) NOT NULL,
    CONSTRAINT uq_colleges_short_name_city UNIQUE (short_name, city),
    CONSTRAINT ck_colleges_latitude  CHECK (latitude  BETWEEN -90  AND 90),
    CONSTRAINT ck_colleges_longitude CHECK (longitude BETWEEN -180 AND 180)
);

CREATE TABLE users (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email          VARCHAR(254) NOT NULL,
    password_hash  VARCHAR(100) NOT NULL,
    role           VARCHAR(20)  NOT NULL,
    status         VARCHAR(20)  NOT NULL DEFAULT 'ACTIVE',
    status_reason  VARCHAR(300),
    display_name   VARCHAR(60)  NOT NULL,
    phone          VARCHAR(20),
    created_at     TIMESTAMPTZ  NOT NULL DEFAULT now(),
    last_login_at  TIMESTAMPTZ,
    CONSTRAINT uq_users_email           UNIQUE (email),
    -- The application lower-cases emails; this guarantees "A@x.com" and "a@x.com" can never both exist.
    CONSTRAINT ck_users_email_lowercase CHECK (email = lower(email)),
    CONSTRAINT ck_users_role            CHECK (role IN ('STUDENT', 'OWNER', 'ADMIN')),
    CONSTRAINT ck_users_status          CHECK (status IN ('ACTIVE', 'SUSPENDED'))
);

-- One row per student account (1:1 with users). Every field is optional until the student fills it in.
CREATE TABLE student_profiles (
    user_id        BIGINT PRIMARY KEY REFERENCES users (id) ON DELETE CASCADE,
    college_id     BIGINT REFERENCES colleges (id),
    course         VARCHAR(80),
    year_of_study  SMALLINT,
    gender         VARCHAR(20),
    CONSTRAINT ck_student_year   CHECK (year_of_study BETWEEN 1 AND 6),
    CONSTRAINT ck_student_gender CHECK (gender IN ('FEMALE', 'MALE', 'OTHER'))
);

-- One row per owner account (1:1 with users). Verification fields are changed only by administrators.
CREATE TABLE owner_profiles (
    user_id              BIGINT PRIMARY KEY REFERENCES users (id) ON DELETE CASCADE,
    owner_type           VARCHAR(20) NOT NULL DEFAULT 'INDIVIDUAL',
    business_name        VARCHAR(120),
    verification_status  VARCHAR(20) NOT NULL DEFAULT 'UNVERIFIED',
    verified_at          TIMESTAMPTZ,
    verified_by          BIGINT REFERENCES users (id),
    CONSTRAINT ck_owner_type         CHECK (owner_type IN ('INDIVIDUAL', 'PG_OPERATOR', 'HOSTEL_OPERATOR')),
    CONSTRAINT ck_owner_verification CHECK (verification_status IN ('UNVERIFIED', 'PENDING', 'VERIFIED', 'REJECTED'))
);

CREATE INDEX ix_student_profiles_college ON student_profiles (college_id);

