-- Fare rules used to ESTIMATE monthly transport cost. Every row records where the number came from and since when.
-- Administrators maintain this table (add / remove rules) when fares change.
--   PER_TRIP_METERED : fare = base_fare for the first base_km, then per_km for each further km (auto-rickshaw)
--   PER_TRIP_SLAB    : fare = base_fare for trips up to up_to_km (bus fare slabs)
--   MONTHLY_PASS_SLAB: monthly pass price = base_fare for rail distance up to up_to_km (local train)
CREATE TABLE fare_rules (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    mode            VARCHAR(20)   NOT NULL,
    kind            VARCHAR(20)   NOT NULL,
    up_to_km        NUMERIC(6, 2),
    base_fare       NUMERIC(8, 2) NOT NULL,
    base_km         NUMERIC(6, 2),
    per_km          NUMERIC(8, 2),
    description     VARCHAR(200)  NOT NULL,
    source_name     VARCHAR(200)  NOT NULL,
    source_url      VARCHAR(500),
    effective_from  DATE          NOT NULL,
    created_at      TIMESTAMPTZ   NOT NULL DEFAULT now(),
    CONSTRAINT ck_fare_mode CHECK (mode IN ('AUTO_RICKSHAW', 'BUS', 'LOCAL_TRAIN')),
    CONSTRAINT ck_fare_kind CHECK (kind IN ('PER_TRIP_METERED', 'PER_TRIP_SLAB', 'MONTHLY_PASS_SLAB')),
    CONSTRAINT ck_fare_amounts CHECK (base_fare >= 0 AND (per_km IS NULL OR per_km >= 0)),
    CONSTRAINT ck_fare_shape CHECK (
        (kind = 'PER_TRIP_METERED' AND base_km IS NOT NULL AND per_km IS NOT NULL)
        OR (kind IN ('PER_TRIP_SLAB', 'MONTHLY_PASS_SLAB') AND up_to_km IS NOT NULL))
);

