CREATE TABLE listings (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_id           BIGINT        NOT NULL REFERENCES users (id),
    title              VARCHAR(120)  NOT NULL,
    description        VARCHAR(4000),
    property_type      VARCHAR(20)   NOT NULL DEFAULT 'PG',
    gender_policy      VARCHAR(20)   NOT NULL DEFAULT 'ANY',
    address_line       VARCHAR(300),
    locality           VARCHAR(100),
    city               VARCHAR(80)   NOT NULL DEFAULT 'Mumbai',
    pincode            VARCHAR(6),
    latitude           NUMERIC(9, 6),
    longitude          NUMERIC(9, 6),
    status             VARCHAR(30)   NOT NULL DEFAULT 'DRAFT',
    -- Latest message from an administrator (why changes were requested, or why rejected / suspended).
    status_reason      VARCHAR(1000),
    submitted_at       TIMESTAMPTZ,
    published_at       TIMESTAMPTZ,
    -- When the owner last confirmed rooms and availability are correct (used for "freshness").
    last_confirmed_at  TIMESTAMPTZ,
    is_sample_data     BOOLEAN       NOT NULL DEFAULT FALSE,
    created_at         TIMESTAMPTZ   NOT NULL DEFAULT now(),
    updated_at         TIMESTAMPTZ   NOT NULL DEFAULT now(),
    -- Optimistic locking: stops an owner's edit and an admin's decision silently overwriting each other.
    version            BIGINT        NOT NULL DEFAULT 0,
    CONSTRAINT ck_listings_property_type CHECK (property_type IN ('PG', 'HOSTEL', 'FLAT', 'ROOM')),
    CONSTRAINT ck_listings_gender_policy CHECK (gender_policy IN ('ANY', 'FEMALE_ONLY', 'MALE_ONLY')),
    CONSTRAINT ck_listings_status CHECK (status IN ('DRAFT', 'PENDING_VERIFICATION', 'CHANGES_REQUESTED',
        'PUBLISHED_AVAILABLE', 'PUBLISHED_UNAVAILABLE', 'SUSPENDED', 'REJECTED')),
    CONSTRAINT ck_listings_pincode   CHECK (pincode ~ '^[1-9][0-9]{5}$'),
    CONSTRAINT ck_listings_latitude  CHECK (latitude  BETWEEN -90  AND 90),
    CONSTRAINT ck_listings_longitude CHECK (longitude BETWEEN -180 AND 180)
);

CREATE INDEX ix_listings_owner       ON listings (owner_id);
CREATE INDEX ix_listings_status_city ON listings (status, city);

-- Each listing offers one or more room types, each with its own rent and bed availability.
CREATE TABLE room_options (
    id                       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    listing_id               BIGINT      NOT NULL REFERENCES listings (id) ON DELETE CASCADE,
    room_type                VARCHAR(20) NOT NULL,
    sharing_capacity         INTEGER     NOT NULL,
    monthly_rent             INTEGER     NOT NULL,
    security_deposit         INTEGER,
    beds_total               INTEGER     NOT NULL,
    beds_available           INTEGER     NOT NULL,
    availability_updated_at  TIMESTAMPTZ,
    CONSTRAINT ck_rooms_type      CHECK (room_type IN ('SINGLE', 'DOUBLE', 'TRIPLE', 'DORMITORY')),
    CONSTRAINT ck_rooms_sharing   CHECK (sharing_capacity BETWEEN 1 AND 12),
    CONSTRAINT ck_rooms_rent      CHECK (monthly_rent BETWEEN 1 AND 1000000),
    CONSTRAINT ck_rooms_deposit   CHECK (security_deposit >= 0),
    CONSTRAINT ck_rooms_beds      CHECK (beds_total BETWEEN 1 AND 500),
    CONSTRAINT ck_rooms_available CHECK (beds_available BETWEEN 0 AND beds_total)
);

CREATE INDEX ix_room_options_listing_rent ON room_options (listing_id, monthly_rent);

-- Extra costs on top of rent (electricity, food, maintenance...). "mandatory" = every tenant must pay it.
CREATE TABLE listing_charges (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    listing_id   BIGINT      NOT NULL REFERENCES listings (id) ON DELETE CASCADE,
    charge_type  VARCHAR(20) NOT NULL,
    description  VARCHAR(100),
    amount       INTEGER     NOT NULL,
    frequency    VARCHAR(20) NOT NULL,
    mandatory    BOOLEAN     NOT NULL DEFAULT TRUE,
    CONSTRAINT ck_charges_type      CHECK (charge_type IN ('ELECTRICITY', 'MAINTENANCE', 'FOOD', 'WIFI', 'WATER', 'OTHER')),
    CONSTRAINT ck_charges_amount    CHECK (amount BETWEEN 0 AND 1000000),
    CONSTRAINT ck_charges_frequency CHECK (frequency IN ('MONTHLY', 'ONE_TIME'))
);

CREATE INDEX ix_listing_charges_listing ON listing_charges (listing_id);

-- The owner's answer for each amenity. No row = "not specified"; available = false = "confirmed not available".
CREATE TABLE listing_amenities (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    listing_id  BIGINT  NOT NULL REFERENCES listings (id) ON DELETE CASCADE,
    amenity_id  BIGINT  NOT NULL REFERENCES amenities (id),
    available   BOOLEAN NOT NULL,
    CONSTRAINT uq_listing_amenities UNIQUE (listing_id, amenity_id)
);

-- Photo metadata. The image bytes live on disk under a random storage_key, never the uploaded filename.
CREATE TABLE listing_images (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    listing_id    BIGINT      NOT NULL REFERENCES listings (id) ON DELETE CASCADE,
    storage_key   VARCHAR(100) NOT NULL,
    content_type  VARCHAR(30) NOT NULL,
    size_bytes    INTEGER     NOT NULL,
    width         INTEGER     NOT NULL,
    height        INTEGER     NOT NULL,
    uploaded_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT uq_listing_images_key UNIQUE (storage_key)
);

CREATE INDEX ix_listing_images_listing ON listing_images (listing_id);

-- Audit trail: one row for every status change, with who did it and why.
CREATE TABLE listing_status_history (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    listing_id   BIGINT      NOT NULL REFERENCES listings (id) ON DELETE CASCADE,
    from_status  VARCHAR(30),
    to_status    VARCHAR(30) NOT NULL,
    actor_id     BIGINT      REFERENCES users (id),
    reason       VARCHAR(1000),
    created_at   TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX ix_listing_status_history_listing ON listing_status_history (listing_id, created_at);
