-- V2 (Phase 3): accommodation listings and everything that belongs to one listing.
-- Money is stored as whole rupees (INTEGER): rents are never fractional and integers avoid rounding errors.

-- Reference list of amenities. "Core" amenities must be answered (yes/no) before a listing can be submitted,
-- so the suitability score never has to guess about the most important ones.
CREATE TABLE amenities (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code        VARCHAR(40) NOT NULL,
    name        VARCHAR(80) NOT NULL,
    is_core     BOOLEAN     NOT NULL DEFAULT FALSE,
    sort_order  INTEGER     NOT NULL DEFAULT 0,
    CONSTRAINT uq_amenities_code UNIQUE (code)
);

